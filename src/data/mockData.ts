const img = (seed: string, w = 800, h = 600) =>
  `https://picsum.photos/seed/${seed}/${w}/${h}`;

function makeFlight(
  airline: string,
  from: string,
  code: string,
  to: string,
  code2: string,
  dep: string,
  arr: string,
  dur: string,
  stops: number,
): FlightDetails {
  const num = Math.floor(1000 + Math.random() * 9000);
  return {
    airline,
    flightNumber: `${airline.slice(0, 2).toUpperCase()}${num}`,
    departure: { airport: from, code, time: dep },
    arrival: { airport: to, code: code2, time: arr },
    duration: dur,
    stops,
    returnFlight: {
      airline,
      flightNumber: `${airline.slice(0, 2).toUpperCase()}${num + 1}`,
      departure: { airport: to, code: code2, time: '14:30' },
      arrival: { airport: from, code, time: '17:15' },
      duration: dur,
      stops,
    },
  };
}

function makeRooms(prices: number[]): RoomType[] {
  const names = ['Standard Room', 'Superior Room', 'Deluxe Suite', 'Family Suite'];
  const features = [
    ['En-suite bathroom', 'Air conditioning', 'TV'],
    ['Sea view', 'Balcony', 'Minibar', 'Coffee machine'],
    ['Separate living area', 'Jacuzzi bath', 'Premium toiletries', 'King-size bed'],
    ['Two bedrooms', 'Kitchenette', 'Sofa bed', 'Highchair available'],
  ];
  return prices.map((price, i) => ({
    id: `room-${i + 1}`,
    name: names[i],
    occupancy: i < 2 ? 2 : i === 2 ? 2 : 4,
    maxOccupancy: i < 2 ? 3 : i === 2 ? 3 : 5,
    image: img(`room-${i + 1}`, 600, 400),
    features: features[i],
    bedType: i === 0 ? 'Double' : i === 1 ? 'King' : i === 2 ? 'King' : '2 x Doubles',
    pricePerNight: price,
    pricePerPerson: Math.round(price / 2),
    available: true,
  }));
}

function makeReviews(reviews: { name: string; rating: number; date: string; comment: string; helpful: number }[]): Review[] {
  return reviews.map((r, i) => ({
    id: `rev-${i + 1}`,
    name: r.name,
    rating: r.rating,
    date: r.date,
    comment: r.comment,
    helpful: r.helpful,
  }));
}

